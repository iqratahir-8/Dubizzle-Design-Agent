#!/usr/bin/env node
/**
 * Generates the Storybook stories for the page templates.
 *
 * Storybook used to carry its own hand-built Home / Search / Ad detail pages, which drifted
 * out of date the moment the kit's templates became frozen captures of the live site. There
 * is now one source: every story below points at the same file design-kit/templates serves,
 * so the two can't disagree. Re-run after adding or capturing a template.
 *
 *   node scripts/build-template-stories.mjs   (part of npm run build:templates)
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TEMPLATES = join(ROOT, 'design-kit/templates');
const OUT = join(ROOT, 'src/templates/PageTemplates.stories.tsx');
const LAYOUTS = ['desktop', 'mobile'];

const { templates } = JSON.parse(readFileSync(join(TEMPLATES, 'live-templates.json'), 'utf8'));

/** Reads the `live-template` meta stamp the template builder writes into each capture. */
function stamp(name, layout) {
  const file = join(TEMPLATES, layout, `${name}.html`);
  if (!existsSync(file)) return null;
  const head = readFileSync(file, 'utf8').slice(0, 4000);
  const meta = head.match(/<meta name="live-template" content="[^"]*·\s*captured ([\d-]+) from ([^">]+)">/);
  return { live: head.includes('LIVE TEMPLATE'), captured: meta?.[1], origin: meta?.[2] };
}

const names = new Set(Object.keys(templates));
for (const layout of LAYOUTS) {
  for (const f of readdirSync(join(TEMPLATES, layout))) if (f.endsWith('.html')) names.add(f.replace(/\.html$/, ''));
}

const titleCase = (n) => n.replace(/-/g, ' ').replace(/^./, (c) => c.toUpperCase());
const pascal = (n) => n.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());

const entries = [];
for (const name of names) {
  const layouts = LAYOUTS.filter((l) => existsSync(join(TEMPLATES, l, `${name}.html`)));
  const info = layouts.map((l) => stamp(name, l)).find(Boolean) ?? {};
  const known = templates[name];
  entries.push({
    name,
    label: known?.label ?? titleCase(name),
    // An account template exists only where the logged-in capture ran, so its story says so
    // rather than showing an empty frame.
    local: Boolean(known?.account),
    live: Boolean(info.live) || (Boolean(known) && layouts.length === 0),
    layouts,
    captured: info.captured,
    origin: info.origin,
    order: Object.keys(templates).indexOf(name),
  });
}
// Manifest order (live captures, in the order they were captured), then hand-built pages.
entries.sort((a, b) => (a.order < 0) - (b.order < 0) || (a.order >= 0 ? a.order - b.order : a.name.localeCompare(b.name)));

const story = (e) => `export const ${pascal(e.name)}: Story = {
  name: ${JSON.stringify(e.label)},
  args: ${JSON.stringify(
    {
      name: e.name,
      label: e.label,
      layouts: e.layouts,
      live: e.live,
      ...(e.local ? { local: true } : {}),
      ...(e.captured ? { captured: e.captured } : {}),
      ...(e.origin ? { origin: e.origin } : {}),
    },
    null,
    2,
  ).replace(/\n/g, '\n  ')},
};`;

const file = `/* GENERATED by scripts/build-template-stories.mjs — do not edit.
   One story per page template in design-kit/templates/, rendering that exact file so Storybook
   and the design kit always show the same page. Re-run: npm run build:templates */
import type { Meta, StoryObj } from '@storybook/react';
import { LiveTemplate } from './LiveTemplate';

const meta: Meta<typeof LiveTemplate> = {
  title: 'Templates/Pages',
  component: LiveTemplate,
  parameters: {
    layout: 'fullscreen',
    docs: {
      description: {
        component:
          'The page templates from \`design-kit/templates/\`. Each story renders the template file itself, so it matches the design kit exactly — **Live capture** pages are frozen copies of dubizzle.com.eg and render like production. Switch **device** between desktop (1440px) and mobile (390px); the frame is scaled to fit. Copy the HTML file to start feature work.',
      },
    },
  },
  argTypes: {
    device: { control: 'inline-radio', options: ['desktop', 'mobile'] },
    name: { table: { disable: true } },
    label: { table: { disable: true } },
    layouts: { table: { disable: true } },
    live: { table: { disable: true } },
    local: { table: { disable: true } },
    captured: { table: { disable: true } },
    origin: { table: { disable: true } },
  },
  args: { device: 'desktop' },
};
export default meta;

type Story = StoryObj<typeof LiveTemplate>;

${entries.map(story).join('\n\n')}
`;

writeFileSync(OUT, file);
const live = entries.filter((e) => e.live).length;
console.log(`stories  ${entries.length} page templates (${live} live, ${entries.length - live} hand-built) → src/templates/PageTemplates.stories.tsx`);

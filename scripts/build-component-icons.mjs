#!/usr/bin/env node
/**
 * Generates src/components/icons/generated.tsx from design-kit icon files, so the React
 * components draw exactly the same SVGs as the kit (and the live site) instead of
 * hand-drawn look-alikes. Monochrome icons are recoloured to currentColor.
 *
 *   npm run build:icons   (also part of npm run sync)
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ICONS = join(ROOT, 'design-kit/icons');
const OUT = join(ROOT, 'src/components/icons');

/** Component name → [kit file, keep original colours?] */
const SET = {
  HeartIcon: ['action/heart.svg', false],
  BedsIcon: ['property/beds.svg', false],
  BathsIcon: ['property/baths.svg', false],
  AreaIcon: ['property/area.svg', false],
  LocationIcon: ['location/location-filled.svg', false],
  LocationOutlineIcon: ['location/location.svg', false],
  PhotoCountIcon: ['media/image-count.svg', false],
  EliteIcon: ['status/elite.svg', true],
  ChevronDownIcon: ['navigation/chevron-down.svg', false],
  FiltersIcon: ['action/filters.svg', false],
  ImagePlaceholderIcon: ['media/image.svg', false],
  // Mobile web — extracted from the live dubizzle.com.eg pages (design-kit/icons/mobile)
  BackIcon: ['mobile/back.svg', false],
  SearchIcon: ['mobile/search.svg', false],
  LocationPinIcon: ['mobile/location-pin.svg', false],
  SortIcon: ['mobile/sort.svg', false],
  SaveSearchIcon: ['mobile/save-search.svg', false],
  NavHomeIcon: ['mobile/nav-home.svg', false],
  NavChatIcon: ['mobile/nav-chat.svg', false],
  NavMyAdsIcon: ['mobile/nav-my-ads.svg', false],
  NavAccountIcon: ['mobile/nav-account.svg', false],
  NavSellIcon: ['mobile/nav-sell.svg', true],
  DubizzleLogo: ['mobile/logo-dubizzle.svg', false],
  VerticalMotorsIcon: ['mobile/vertical-motors.svg', true],
  VerticalPropertyIcon: ['mobile/vertical-property.svg', true],
  AppBannerIcon: ['mobile/banner-app-icon.svg', true],
  CloseIcon: ['mobile/banner-close.svg', false],
  StarIcon: ['mobile/banner-star.svg', true],
  DownloadIcon: ['mobile/banner-download.svg', true],
  CheckIcon: ['mobile/promo-check.svg', false],
  CrownIcon: ['mobile/prime-crown.svg', true],
  ChevronRightIcon: ['navigation/chevron-right.svg', false],
};

let out = `/* GENERATED by scripts/build-component-icons.mjs from design-kit/icons — do not edit. */
import type { SVGProps } from 'react';

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'dangerouslySetInnerHTML'> {
  size?: number;
}
`;

for (const [name, [file, keepColour]] of Object.entries(SET)) {
  const svg = readFileSync(join(ICONS, file), 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 24 24';
  // Keep the file's own root fill (e.g. fill="none"): shapes without a fill inherit it, and
  // forcing currentColor paints them (the Sell button's white ring turned black that way).
  const rootFill = keepColour ? (svg.match(/<svg\b[^>]*\sfill="([^"]+)"/)?.[1] ?? 'currentColor') : 'currentColor';
  let body = svg
    .replace(/^[\s\S]*?<svg\b[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s+/g, ' ')
    .trim();
  if (!keepColour) body = body.replace(/fill="#(?:[0-9a-f]{3}|[0-9a-f]{6})"/gi, 'fill="currentColor"');
  // Paths with no fill inherit the svg's fill, which is set to currentColor below.
  out += `
/** design-kit/icons/${file} */
export function ${name}({ size = 16, ...props }: IconProps) {
  return (
    <svg width={size} height={size} viewBox="${viewBox}" fill="${rootFill}" aria-hidden="true" focusable="false" {...props}
      dangerouslySetInnerHTML={{ __html: ${JSON.stringify(body)} }} />
  );
}
`;
}

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'generated.tsx'), out);
writeFileSync(join(OUT, 'index.ts'), `export * from './generated';\n`);
console.log(`Generated ${Object.keys(SET).length} icons → src/components/icons/generated.tsx`);

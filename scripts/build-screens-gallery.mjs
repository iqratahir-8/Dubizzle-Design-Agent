#!/usr/bin/env node
/**
 * Builds design-kit/reference/live/gallery.html — every captured live screen, grouped,
 * desktop and mobile side by side, each scrollable at full length.
 *
 * Generated from whatever PNGs exist in reference/live/screens/, so it can't list a
 * screen that wasn't captured. Captures are gitignored, so the gallery is too; it is
 * rebuilt at the end of every capture run.
 *
 *   npm run build:gallery
 */
import { readdirSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const LIVE = join(ROOT, 'design-kit/reference/live');
const SCREENS = join(LIVE, 'screens');

const GROUPS = [
  ['Landing pages', { home: 'Home', motors: 'Motors', property: 'Property' }],
  ['Ad detail', { 'car-dpv': 'Car for sale — detail page' }],
  [
    'Post an ad',
    {
      'post-category': 'Choose a category',
      'post-subcategory': 'Choose a subcategory',
      'post-details': 'Ad details form',
      'post-review': 'Review',
      upsell: 'Upselling — sell faster',
      packages: 'Packages',
    },
  ],
  ['My ads', { 'my-ads': 'My Ads' }],
  ['Chat', { chat: 'Chats inbox' }],
  [
    'Profile & settings',
    {
      'edit-profile': 'Edit profile',
      'settings-privacy': 'Settings — privacy',
      'settings-notifications': 'Settings — notifications',
    },
  ],
];

export function buildGallery() {
  if (!existsSync(SCREENS)) return 0;
  const files = readdirSync(SCREENS).filter((f) => f.endsWith('.png'));
  // name.layout.png, plus name.layout.<variant>.png (e.g. the mobile app-install prompt)
  const shots = new Map();
  for (const file of files) {
    const [name, layout, ...rest] = file.replace(/\.png$/, '').split('.');
    const key = rest.length ? `${name}:${rest.join('.')}` : name;
    if (!shots.has(key)) shots.set(key, {});
    shots.get(key)[layout] = file;
  }

  const known = new Set(GROUPS.flatMap(([, items]) => Object.keys(items)));
  const others = [...new Set([...shots.keys()].map((k) => k.split(':')[0]))].filter((n) => !known.has(n));
  const groups = [...GROUPS, ...(others.length ? [['Other', Object.fromEntries(others.map((n) => [n, n]))]] : [])];

  const frame = (file, layout) =>
    file
      ? `<figure class="shot shot--${layout}">
          <figcaption>${layout} <a href="screens/${file}" target="_blank">open full size</a></figcaption>
          <div class="shot__scroll"><img src="screens/${file}" alt="" loading="lazy"></div>
        </figure>`
      : `<figure class="shot shot--${layout} shot--missing"><figcaption>${layout}</figcaption><p>Not captured yet</p></figure>`;

  let captured = 0;
  const sections = groups
    .map(([title, items]) => {
      const cards = Object.entries(items)
        .map(([name, label]) => {
          const base = shots.get(name);
          const variants = [...shots.keys()].filter((k) => k.startsWith(`${name}:`));
          if (base) captured++;
          const extra = variants
            .map((k) => `<div class="variant"><h4>${label} — ${k.split(':')[1].replace(/-/g, ' ')}</h4><div class="pair">${frame(shots.get(k).desktop, 'desktop')}${frame(shots.get(k).mobile, 'mobile')}</div></div>`)
            .join('');
          return `<article class="screen${base ? '' : ' screen--pending'}">
        <h3>${label}</h3>
        <div class="pair">${frame(base?.desktop, 'desktop')}${frame(base?.mobile, 'mobile')}</div>
        ${extra}
      </article>`;
        })
        .join('\n');
      return `<section><h2>${title}</h2>${cards}</section>`;
    })
    .join('\n');

  const newest = files.length ? new Date(Math.max(...files.map((f) => statSync(join(SCREENS, f)).mtimeMs))) : null;

  writeFileSync(
    join(LIVE, 'gallery.html'),
    `<!doctype html>
<!-- GENERATED by scripts/build-screens-gallery.mjs -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Live screens — dubizzle Egypt</title>
<link rel="stylesheet" href="../../tokens/tokens.css"><link rel="stylesheet" href="../../patterns/patterns.css">
<style>
  body { background: var(--surface-subtle); }
  .wrap { max-width: 150rem; margin-inline: auto; padding: var(--space-6); }
  .lede { color: var(--text-secondary); font-size: var(--text-sm); margin: var(--space-2) 0 var(--space-6); max-width: 80rem; }
  nav.jump { display: flex; flex-wrap: wrap; gap: var(--space-2); margin-bottom: var(--space-6); }
  section { margin-bottom: var(--space-8); }
  section > h2 { font-size: var(--text-2xl); margin: 0 0 var(--space-4); }
  .screen { background: var(--surface-card); border: 0.1rem solid var(--border-default); border-radius: var(--radius-lg); padding: var(--space-4); margin-bottom: var(--space-4); }
  .screen h3 { font-size: var(--text-lg); margin: 0 0 var(--space-3); }
  .screen--pending h3 { color: var(--text-tertiary); }
  .variant h4 { font-size: var(--text-sm); color: var(--text-secondary); margin: var(--space-4) 0 var(--space-2); }
  .pair { display: grid; grid-template-columns: minmax(0, 1fr) 30rem; gap: var(--space-4); align-items: start; }
  .shot { margin: 0; }
  .shot figcaption { display: flex; justify-content: space-between; font-size: var(--text-xs); color: var(--text-tertiary); text-transform: uppercase; margin-bottom: var(--space-1); }
  .shot figcaption a { color: var(--color-secondary); text-transform: none; }
  .shot__scroll { height: 60rem; overflow-y: auto; border: 0.1rem solid var(--border-default); border-radius: var(--radius-md); background: var(--surface-page); }
  .shot__scroll img { display: block; width: 100%; height: auto; }
  .shot--missing p { height: 12rem; margin: 0; display: flex; align-items: center; justify-content: center; border: 0.1rem dashed var(--border-strong); border-radius: var(--radius-md); color: var(--text-tertiary); font-size: var(--text-sm); }
  @media (max-width: 950px) { .pair { grid-template-columns: minmax(0, 1fr); } }
</style></head>
<body><div class="wrap">
  <h1 class="page-head__title">Live screens</h1>
  <p class="lede">
    ${captured} screens captured from dubizzle.com.eg${newest ? `, latest ${newest.toISOString().slice(0, 16).replace('T', ' ')}` : ''}.
    Each frame scrolls through the full page. Account screens use sample names, messages and contact details — no real personal data.
    Re-capture with <code>npm run capture:rendered</code> (public pages) and <code>npm run capture:account</code> (logged-in).
  </p>
  <nav class="jump">${groups.map(([t]) => `<a class="chip" href="#${t.toLowerCase().replace(/[^a-z]+/g, '-')}">${t}</a>`).join('')}</nav>
${sections.replace(/<section><h2>([^<]+)<\/h2>/g, (_, t) => `<section id="${t.toLowerCase().replace(/[^a-z]+/g, '-')}"><h2>${t}</h2>`)}
</div></body></html>
`,
  );
  return captured;
}

if (process.argv[1]?.endsWith('build-screens-gallery.mjs')) {
  const n = buildGallery();
  console.log(`Built design-kit/reference/live/gallery.html — ${n} screens`);
}

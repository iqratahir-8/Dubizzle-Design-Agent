const packageRoots = config.packageRoots.map((p) => join(monorepo, p));
const entry = join(monorepo, config.entryVariables);

const raw = collectVariables(entry, packageRoots);
const resolved = resolveAll(raw);

// Breakpoints live in their own file, outside the variables import chain.
const breakpointFile = join(monorepo, 'frontend/horizontal/horizontal/styles/deviceWidths.css');
if (existsSync(breakpointFile)) {
  for (const [key, value] of collectVariables(breakpointFile, packageRoots)) {
    resolved.set(key, resolveValue(value, raw));
  }
}

const COLOR_VALUE = /^(#[0-9a-f]{3,8}|rgba?\(|hsla?\(|white$|black$|transparent$|linear-gradient|radial-gradient)/i;

/**
 * PostCSS evaluated bare arithmetic at build time (`$containerMargin: 2 * $largeSpacing`),
 * but CSS custom properties don't — an unwrapped expression silently breaks the consumer.
 * Wrap anything that is purely numbers, units and operators.
 */
function normalizeArithmetic(value) {
  if (value.startsWith('calc(')) return value;
  const hasOperator = /\s[*/+]\s/.test(value);
  const isPureMath =
    value.replace(/-?[\d.]+(rem|px|em|%|vh|vw|ms|s)?/g, '').replace(/[\s()+*/-]/g, '') === '';
  return hasOperator && isPureMath ? `calc(${value})` : value;
}

function classify(name, value) {
  if (/^deviceWidth/.test(name)) return 'breakpoint';
  if (/shadow/i.test(name)) return 'shadow';
  if (/fontWeight/i.test(name)) return 'font-weight';
  if (/fontSize|FontSize/.test(name)) return 'font-size';
  if (/^font|fontFamily/i.test(name)) return 'font-family';
  if (/lineHeight|letterSpacing/i.test(name)) return 'typography';
  if (/radius/i.test(name)) return 'radius';
  if (COLOR_VALUE.test(value)) return 'color';
  if (/spacing|padding|margin|gap/i.test(name)) return 'spacing';
  if (/width|height|size/i.test(name)) return 'size';
  if (/zindex|z-index/i.test(name)) return 'z-index';
  return 'other';
}

const groups = new Map();
/* A handful of tokens are url() references to bitmaps that live in the monorepo's
   asset folders. Emitting them would make every bundler try (and fail) to resolve a
   path we don't ship, so they're recorded in tokens.json instead of the stylesheet. */
const assetRefs = {};

for (const [name, rawValue] of [...resolved].sort(([a], [b]) => a.localeCompare(b))) {
  const value = normalizeArithmetic(rawValue);
  const cssName = `--${toKebab(name)}`;
  if (/\burl\(/.test(value)) {
    assetRefs[cssName] = value;
    continue;
  }
  const kind = classify(name, value);
  if (!groups.has(kind)) groups.set(kind, []);
  groups.get(kind).push({ name, cssName, value, kind });
}

const ORDER = [
  'color',
  'font-family',
  'font-size',
  'font-weight',
  'typography',
  'spacing',
  'radius',
  'shadow',
  'size',
  'breakpoint',
  'z-index',
  'other',
];

const outDir = join(ROOT, 'design-kit/tokens');
mkdirSync(outDir, { recursive: true });

// ── tokens.css — every production token, resolved, grouped ─────────────────
let css = `/* GENERATED by scripts/sync-tokens.mjs — do not edit by hand.
   Source: ${config.brand} variables chain (strat -> horizontal -> dubizzle-facelift -> dubizzle-eg)
   Regenerate with: npm run sync:tokens
   ${resolved.size} tokens resolved. */

:root {
`;
for (const kind of ORDER) {
  const entries = groups.get(kind);
  if (!entries?.length) continue;
  css += `\n  /* ── ${kind} (${entries.length}) ── */\n`;
  for (const { cssName, value } of entries) {
    css += `  ${cssName}: ${value};\n`;
  }
}

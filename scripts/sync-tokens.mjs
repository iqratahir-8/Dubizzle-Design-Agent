// Fail loudly if an upstream rename broke a mapping, rather than emitting dead vars.
const emitted = new Set([...groups.values()].flat().map((t) => t.cssName));
const missing = [];
for (const group of Object.values(SEMANTIC)) {
  for (const [alias, expression] of Object.entries(group)) {
    for (const [whole, ref] of expression.matchAll(/var\((--[a-z0-9-]+)(\s*,[^)]*)?\)/g)) {
      const hasFallback = whole.includes(',');
      if (!emitted.has(ref) && !hasFallback) missing.push(`${alias} -> ${ref}`);
    }
  }
}

css += `\n  /* ══ SEMANTIC API — target these, not the production tokens above ══ */\n`;
for (const [groupName, entries] of Object.entries(SEMANTIC)) {
  css += `\n  /* ── ${groupName} ── */\n`;
  for (const [alias, expression] of Object.entries(entries)) {
    css += `  ${alias}: ${expression};\n`;
  }
}

css += '}\n';
/* Kit pages and templates link tokens.css and nothing else, so the kit's copy pulls in the
   web fonts — without them the kit renders in the system fallback, ~3px wider per word than
   Storybook (which is how npm run check:parity found this). The library gets its faces from
   src/tokens/index.css instead, so its copy stays token-only. */
const FONT_IMPORT = `/* Web fonts — see design-kit/tokens/fonts.css */\n@import url('./fonts.css');\n\n`;
writeFileSync(join(outDir, 'tokens.css'), css.replace(':root {', `${FONT_IMPORT}:root {`));

/* The React library and the static design kit must never disagree about what a token
   means, so both read the same generated file rather than keeping parallel copies. */
const libTokens = join(ROOT, 'src/tokens/generated.css');
mkdirSync(dirname(libTokens), { recursive: true });
writeFileSync(libTokens, css);

if (missing.length) {
  console.warn(`\n⚠️  ${missing.length} semantic alias(es) point at tokens that no longer exist upstream:`);
  for (const m of missing) console.warn(`     ${m}`);
  console.warn('     Update the SEMANTIC map in scripts/sync-tokens.mjs.');
}


